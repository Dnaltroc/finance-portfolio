"""Variance Report: actuals vs budget -> F/U summary, department bridge, flags, commentary."""

from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

import fp_ui as ui
from finlib.models.variance import Thresholds, commentary, waterfall
from projects.variance.cli import HERE, build_variance, load_thresholds, write_variance

ui.page_setup("Budget versus actual",
              "Two general-ledger exports in, the monthly close pack out: sign-correct variances, a bridge "
              "from budgeted to actual net income, the lines worth explaining, and a first draft of the commentary.",
              number="02", section="Variance report")

SAMPLE = HERE / "sample_data"
DEFAULT_TH = load_thresholds(HERE / "config.yaml")

# ---------------------------------------------------------------- inputs ------------
sb = st.sidebar
sb.header("Inputs")
up_a = sb.file_uploader("actuals.csv", type="csv", help="Columns: period, department, account, account_type, amount")
up_b = sb.file_uploader("budget.csv", type="csv")
uploaded = up_a is not None and up_b is not None
if (up_a is None) != (up_b is None):
    sb.warning("Upload both files to use your data; showing the sample until then.")
actuals_raw = pd.read_csv(up_a) if uploaded else pd.read_csv(SAMPLE / "actuals.csv")
budget_raw = pd.read_csv(up_b) if uploaded else pd.read_csv(SAMPLE / "budget.csv")

periods = sorted(set(actuals_raw.get("period", pd.Series(dtype=str)).astype(str))
                 & set(budget_raw.get("period", pd.Series(dtype=str)).astype(str)), reverse=True)
if not periods:
    st.error("The two files share no `period` values (or a file has no `period` column).")
    st.stop()
period = sb.selectbox("Period", periods)
sb.subheader("Flag a line when either rule trips")
abs_amount = sb.slider("Absolute variance at least ($)", 0, 200_000, int(DEFAULT_TH.abs_amount), 5_000,
                       format="$%d")
pct = sb.slider("Or variance % at least", 0, 100, int(round(DEFAULT_TH.pct * 100)), 1, format="%d%%")
top_n = sb.slider("Lines on the Flags sheet", 1, 30, DEFAULT_TH.top_n)
th = Thresholds(abs_amount=float(abs_amount), pct=pct / 100, top_n=top_n)

try:
    pack = build_variance(actuals_raw, budget_raw, period, th)
except Exception as e:  # validation errors list every bad row
    st.error(f"Input problem:\n\n```\n{e}\n```")
    st.stop()

if uploaded:
    ui.upload_badge([up_a.name, up_b.name], f"period {period}.")
else:
    ui.sample_badge("Generated by `projects/variance/make_sample_data.py` with four planted stories.")

# ---------------------------------------------------------------- summary -----------
for col, (_, r) in zip(st.columns(3), pack.summary.iterrows()):
    with col:
        verdict = {"F": "favorable", "U": "unfavorable"}.get(r["fav_unfav"], "on budget")
        st.metric(f"{r['line']}, {period} · {verdict}", ui.fmt_usd(r["actual"]),
                  # st.metric reads direction from a leading sign, so the delta is signed, not parenthesized
                  delta=f"{'-' if r['variance_amt'] < 0 else '+'}${abs(r['variance_amt']):,.0f} "
                        f"({ui.fmt_pct(None if pd.isna(r['variance_pct']) else abs(r['variance_pct']))})",
                  delta_color="normal" if r["line"] != "Expenses" else "inverse",
                  delta_description=f"budget {ui.fmt_usd(r['budget'])}", border=True, height="stretch")
ui.source("variance = actual − budget. Revenue over budget is favorable; expenses over budget are "
          "unfavorable. Net % is NM when budgeted net is zero or a loss.")

# ---------------------------------------------------------------- waterfall ---------
ui.exhibit(1, f"From budgeted to actual net income, {period}")
w = waterfall(pack.detail)
fig = go.Figure(go.Waterfall(
    x=w["step"], y=w["amount"],
    measure=["absolute" if k == "total" else "relative" for k in w["kind"][:-1]] + ["total"],
    text=[ui.fmt_usd(v) for v in w["amount"]], textposition="outside",
    increasing=dict(marker=dict(color=ui.GOOD)), decreasing=dict(marker=dict(color=ui.CRITICAL)),
    totals=dict(marker=dict(color=ui.NAVY)), connector=dict(line=dict(color=ui.AXIS, width=1, dash="dot")),
    textfont=dict(color=ui.INK, size=12), cliponaxis=False,
    hovertemplate="%{x}<br>%{text}<extra></extra>",
))
ui.show(ui.style(fig, height=360, y_title="Net income ($)", y_format="$,.0f"))
ui.source("department contribution variance (revenue minus expense). Green steps helped net income against "
          "budget, red steps hurt it; the steps sum exactly to the Net variance.")

with st.expander("By department (contribution)", icon=":material/table_rows:"):
    d = pack.by_dept
    st.dataframe(pd.DataFrame({
        "Department": d["department"], "Actual contribution": d["actual"].map(ui.fmt_usd),
        "Budget contribution": d["budget"].map(ui.fmt_usd), "Variance": d["variance_amt"].map(ui.fmt_usd),
        "Variance %": d["variance_pct"].map(ui.fmt_pct), "F/U": d["fav_unfav"],
    }), hide_index=True, width="stretch")

# ---------------------------------------------------------------- flags -------------
ui.exhibit(2, "Lines worth explaining")
st.caption(f"{len(pack.flags)} lines flagged. Rule: {pack.thresholds_text}; top {th.top_n} by absolute dollars. "
           "Type a driver for each; the commentary and both downloads pick it up.")
f = pack.flags
view = pd.DataFrame({
    "Department": f["department"], "Account": f["account"], "Type": f["account_type"],
    "Actual": f["actual"].map(ui.fmt_usd), "Budget": f["budget"].map(ui.fmt_usd),
    "Variance": f["variance_amt"].map(ui.fmt_usd), "Variance %": f["variance_pct"].map(ui.fmt_pct),
    "F/U": f["fav_unfav"].map({"F": "▲ Favorable", "U": "▼ Unfavorable", "-": "On budget"}),
    "Driver": f["driver"],
})
edited = st.data_editor(
    view, hide_index=True, width="stretch", key=f"drivers_{period}",
    disabled=[c for c in view.columns if c != "Driver"],
    column_config={"Driver": st.column_config.TextColumn("Driver", width="large",
                                                         help="What caused the variance, in a few words")},
)
pack.flags = f.assign(driver=edited["Driver"].fillna("").astype(str).values)

# ---------------------------------------------------------------- commentary --------
ui.exhibit(3, "Draft commentary")
md = commentary(pack.flags, period)
st.markdown(md.split("\n", 2)[2])

xlsx, xname = ui.build_file(lambda out: write_variance(pack, out)[0])
c1, c2 = st.columns(2)
c1.download_button("Download Excel pack", xlsx, file_name=xname, mime=ui.XLSX_MIME,
                   icon=":material/download:", type="primary", width="stretch")
c2.download_button("Download commentary (.md)", md.encode("utf-8"), file_name=f"commentary_{period}.md",
                   mime="text/markdown", icon=":material/description:", width="stretch")
st.caption("Same files as `python -m projects.variance run`: Summary, Flags (with your drivers), Detail, "
           "Inputs; plus the commentary markdown.")
